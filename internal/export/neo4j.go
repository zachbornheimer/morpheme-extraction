// Package export provides functionality to export semantic graph to various formats
package export

import (
	"fmt"
	"os"

	"github.com/zachbornheimer/morpheme-extraction/internal/graph"
)

// ExportToCypher exports the semantic graph to Cypher statements for Neo4j
// Creates nodes for words and relationships for edges with weights
func ExportToCypher(g *graph.SemanticGraph, outputPath string) error {
	f, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}
	defer f.Close()

	// Write header
	fmt.Fprintln(f, "// Neo4j Cypher statements for Semantic Graph")
	fmt.Fprintln(f, "// Generated by morpheme-extraction")
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "// Clear existing data (optional)")
	fmt.Fprintln(f, "MATCH (n) DETACH DELETE n;")
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "// Create nodes (Words)")

	// Export nodes
	nodeCount := 0
	nodes := g.GetAllNodes()
	for _, node := range nodes {
		if node.Word() == nil {
			continue
		}

		word := node.Word().Str
		wordID := node.Word().ID
		centerFreq := node.Word().Frequency.GetCenter()

		// Escape single quotes in word
		escapedWord := escapeForCypher(word)

		fmt.Fprintf(f, "CREATE (w%d:Word {id: %d, text: '%s', centerFreq: %d});\n",
			wordID, wordID, escapedWord, centerFreq)
		nodeCount++
	}

	fmt.Fprintf(f, "\n// Created %d word nodes\n", nodeCount)
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "// Create relationships (Edges)")

	// Export edges
	edgeCount := 0
	for _, node := range nodes {
		if node.Word() == nil {
			continue
		}

		neighbors := node.GetNeighborsWithWeights()
		for neighborID, weight := range neighbors {
			// Only write each edge once (avoid duplicates)
			if node.Word().ID < neighborID {
				fmt.Fprintf(f, "MATCH (a:Word {id: %d}), (b:Word {id: %d}) CREATE (a)-[:RELATED {weight: %.1f}]->(b);\n",
					node.Word().ID, neighborID, weight)
				edgeCount++
			}
		}
	}

	fmt.Fprintf(f, "\n// Created %d relationships\n", edgeCount)
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "// Create indexes for performance")
	fmt.Fprintln(f, "CREATE INDEX word_id_index IF NOT EXISTS FOR (w:Word) ON (w.id);")
	fmt.Fprintln(f, "CREATE INDEX word_text_index IF NOT EXISTS FOR (w:Word) ON (w.text);")

	return nil
}

// escapeForCypher escapes single quotes for Cypher strings
func escapeForCypher(s string) string {
	result := ""
	for _, ch := range s {
		if ch == '\'' {
			result += "\\'"
		} else if ch == '\\' {
			result += "\\\\"
		} else {
			result += string(ch)
		}
	}
	return result
}
